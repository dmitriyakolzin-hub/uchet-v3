// ОПиУ: выручка → себестоимость → валовая прибыль → расходы → прибыль; колонки по месяцам.
import { columnsReport } from "./dds.js";

export function plReport({ box, ctx }) {
  return columnsReport({
    box, ctx, path: "pl", fileName: "pl", compare: true,
    hint: "Строится по аналитике «Статья ОПиУ» в проводках: доходы — со знаком плюс, расходы — со знаком минус. "
      + "Расход признаётся при начислении (например, Дт 26 / 44), а не при оплате. Щёлкните по сумме статьи — откроются проводки. «Сравнить» — под цифрой синим сумма для сравнения и отклонение (зелёное — лучше, красное — хуже); «Косты» — доля к выручке ОПиУ того же месяца.",
  });
}
